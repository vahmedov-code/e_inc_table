"""Writes include/partition_tables.h from partitions.csv and partitions-big.csv: the binary
tables the firmware writes at 0x8000 when it moves to the larger slots over the air (0.4.8+).
Needs gen_esp32part.py from the ESP32 Arduino core (path as the first argument)."""
import subprocess, sys, tempfile
from pathlib import Path

root = Path(__file__).resolve().parents[1]
gen = sys.argv[1] if len(sys.argv) > 1 else 'gen_esp32part.py'
out = ['#pragma once', '#include <stdint.h>', '// Generated by tools/make_partition_tables.py from partitions.csv and partitions-big.csv.']
for name, csv in (('FACTORY_TABLE', 'partitions.csv'), ('BIG_TABLE', 'partitions-big.csv')):
    with tempfile.TemporaryDirectory() as d:
        b = Path(d) / 't.bin'
        subprocess.run([sys.executable, gen, '--quiet', str(root / csv), str(b)], check=True)
        data = b.read_bytes()
    assert len(data) == 3072, len(data)
    out.append(f'alignas(4) const uint8_t {name}[{len(data)}] = {{' + ','.join(str(x) for x in data) + '};')
(root / 'include/partition_tables.h').write_text('\n'.join(out) + '\n')
print('include/partition_tables.h written')
