"""Packs assets/templates/{open,closed,soon}.png (800x480, exactly the four panel colours) into
include/templates.h: panel frame format, run-length encoded (decoder: include/template_rle.h).
Run after editing a template PNG; the firmware build does not run it."""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
PAL = {(0, 0, 0): 0, (255, 255, 255): 1, (255, 213, 0): 2, (196, 30, 35): 3}
QR_BOX = (681, 290, 99)  # x, y, size of the square left white for the live QR code


def pack(path):
    img = Image.open(path).convert('RGB')
    assert img.size == (800, 480), f'{path}: must be 800x480'
    raw = img.tobytes()
    px = [tuple(raw[i:i + 3]) for i in range(0, len(raw), 3)]
    bad = {p for p in px if p not in PAL}
    assert not bad, f'{path}: colours outside the panel palette, e.g. {sorted(bad)[:3]}'
    out = bytearray(96000)
    for i, p in enumerate(px):
        out[i >> 2] |= PAL[p] << (6 - 2 * (i % 4))
    return bytes(out)


def rle(data):
    # Control byte n < 128: n+1 literal bytes follow. n >= 128: the next byte repeats n-125 times (3..130).
    out, lit, i = bytearray(), bytearray(), 0
    def flush():
        while lit:
            chunk = lit[:128]; del lit[:128]
            out.append(len(chunk) - 1); out.extend(chunk)
    while i < len(data):
        run = 1
        while i + run < len(data) and data[i + run] == data[i] and run < 130:
            run += 1
        if run >= 3:
            flush(); out.append(run + 125); out.append(data[i]); i += run
        else:
            lit.append(data[i]); i += 1
            if len(lit) == 128: flush()
    flush()
    return bytes(out)


def unrle(data):
    out, i = bytearray(), 0
    while i < len(data):
        n = data[i]; i += 1
        if n < 128: out.extend(data[i:i + n + 1]); i += n + 1
        else: out.extend(data[i:i + 1] * (n - 125)); i += 1
    return bytes(out)


lines = ['#pragma once', '// Generated by tools/make_templates.py from assets/templates/*.png. Do not edit.',
         '#include <stdint.h>', '#include <stddef.h>', '',
         '// Square kept white in every template for the live QR code; the caption is part of the image.',
         f'constexpr int QR_BOX_X={QR_BOX[0]},QR_BOX_Y={QR_BOX[1]},QR_BOX_SIZE={QR_BOX[2]};', '']
names = ['open', 'closed', 'soon']
sums = []
for name in names:
    frame = pack(root / 'assets/templates' / f'{name}.png')
    packed = rle(frame)
    assert unrle(packed) == frame
    print(f'{name}: {len(packed)} bytes ({len(packed) * 100 // len(frame)} % of the frame)')
    body = ',\n'.join(','.join(str(b) for b in packed[j:j + 40]) for j in range(0, len(packed), 40))
    lines += [f'static const uint8_t TEMPLATE_{name.upper()}[{len(packed)}]={{', body, '};']
    sums.append(sum((i % 251 + 1) * b for i, b in enumerate(frame)) % 4294967291)
lines += ['', '// Indexed by status: 0 open, 1 closed, 2 soon.',
          'static const uint8_t* const TEMPLATES[3]={' + ','.join(f'TEMPLATE_{n.upper()}' for n in names) + '};',
          'static const size_t TEMPLATE_SIZES[3]={' + ','.join(f'sizeof(TEMPLATE_{n.upper()})' for n in names) + '};',
          '// Weighted sums of the decoded frames, for tools/test_compose.cpp.',
          'static const uint64_t TEMPLATE_SUMS[3]={' + ','.join(f'{v}ULL' for v in sums) + '};', '']
(root / 'include/templates.h').write_text('\n'.join(lines))
print('wrote include/templates.h')
